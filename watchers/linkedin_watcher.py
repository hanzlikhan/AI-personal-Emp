import asyncio
import os
import time
import argparse
import sys
from datetime import datetime
from playwright.async_api import async_playwright

# Configuration
WATCH_FOLDER = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "Needs_Action")
USER_DATA_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "linkedin_user_data")

async def monitor_linkedin():
    print("[LINKEDIN] Starting LinkedIn Watcher...")
    async with async_playwright() as p:
        # Launch browser with persistent context
        browser = await p.chromium.launch_persistent_context(
            user_data_dir=USER_DATA_DIR,
            headless=False,
        )
        
        page = await browser.new_page()
        await page.goto("https://www.linkedin.com/messaging/")
        
        print("[LINKEDIN] Please log in if needed.")
        try:
            await page.wait_for_selector(".msg-conversation-listitem", timeout=60000) # Wait for message list
            print("[LINKEDIN] Messaging interface detected.")
        except:
            print("[LINKEDIN] Timeout waiting for messaging interface.")
            return

        print("[LINKEDIN] Monitoring for new messages...")
        
        processed_messages = set()
        
        while True:
            try:
                # Check for unread indicators
                unread_conversations = await page.query_selector_all(".msg-conversation-card__unread-count")
                
                if unread_conversations:
                    for badge in unread_conversations:
                        # Click conversation
                        card = await badge.xpath("./../../..")
                        if card:
                            await card[0].click()
                            await asyncio.sleep(2)
                            
                            # Extract last message
                            msgs = await page.query_selector_all(".msg-s-event-listitem__body")
                            if msgs:
                                last_msg_el = msgs[-1]
                                text = await last_msg_el.innerText()
                                
                                # Simple duplicate check
                                if text not in processed_messages:
                                    print(f"[LINKEDIN] New message: {text[:50]}...")
                                    processed_messages.add(text)
                                    save_to_needs_action(text)
                                    
                await asyncio.sleep(10)
                
            except Exception as e:
                print(f"[LINKEDIN] Error: {e}")
                await asyncio.sleep(10)

def save_to_needs_action(text):
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    filename = f"{timestamp}_linkedin.md"
    filepath = os.path.join(WATCH_FOLDER, filename)
    
    content = f"""---
type: linkedin
received: "{datetime.now().isoformat()}"
status: pending
---

## LinkedIn Message

**Content:**
{text}

---
*Processed by LinkedIn Watcher*
"""
    
    with open(filepath, 'w', encoding='utf-8') as f:
        f.write(content)
    print(f"[LINKEDIN] Saved task: {filename}")

