async def post_update(content):
    print(f"[LINKEDIN] Starting LinkedIn Poster... Content: {content[:30]}...")
    async with async_playwright() as p:
        # Launch browser with persistent context
        browser = await p.chromium.launch_persistent_context(
            user_data_dir=USER_DATA_DIR,
            headless=False,
        )
        
        page = await browser.new_page()
        
        try:
            await page.goto("https://www.linkedin.com/feed/")
            
            # Check login
            try:
                await page.wait_for_selector('.share-box-feed-entry__trigger, button.share-box-feed-entry__trigger', timeout=10000)
                print("[LINKEDIN] Login verified.")
            except:
                print("[LINKEDIN] Not logged in. Please run monitor mode to login first.")
                return

            # Click "Start a post"
            await page.click('.share-box-feed-entry__trigger, button.share-box-feed-entry__trigger')
            print("[LINKEDIN] Opened post modal.")
            
            # Wait for editor
            editor_selector = '.ql-editor, .share-creation-state__text-editor .ql-editor'
            await page.wait_for_selector(editor_selector)
            
            # Type content
            await page.fill(editor_selector, content)
            print("[LINKEDIN] Content typed.")
            
            await asyncio.sleep(2) # Wait for previews

            # Click Post
            post_button_selector = 'button.share-actions__primary-action'
            post_button = await page.query_selector(post_button_selector)
            
            if post_button:
                is_disabled = await post_button.is_disabled()
                if not is_disabled:
                    # UNCOMMENT TO ACTUALLY POST
                    # await post_button.click()
                    print("[LINKEDIN] (SIMULATION) Clicked Post button.") 
                    print("[LINKEDIN] Success! Post would be live.")
                else:
                    print("[LINKEDIN] Post button is disabled. Content might be empty?")
            else:
                print("[LINKEDIN] Post button not found.")

            await asyncio.sleep(3)

        except Exception as e:
            print(f"[LINKEDIN] Error posting: {e}")

if __name__ == "__main__":
    if not os.path.exists(WATCH_FOLDER):
        os.makedirs(WATCH_FOLDER)
    
    parser = argparse.ArgumentParser()
    parser.add_argument("--simulate", action="store_true", help="Simulate an opportunity event")
    parser.add_argument("--post", help="Post content to LinkedIn")
    args = parser.parse_args()

    if args.simulate:
        simulate_opportunity_event()
    elif args.post:
        try:
            asyncio.run(post_update(args.post))
        except Exception as e:
            print(f"[LINKEDIN] Error: {e}")
    else:
        try:
            asyncio.run(monitor_linkedin())
        except KeyboardInterrupt:
            print("[LINKEDIN] Stopped.")
